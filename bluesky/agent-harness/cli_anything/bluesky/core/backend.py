import json as _json
import os
import urllib.error
import urllib.parse as _urlparse
import urllib.request
from datetime import datetime, timezone

API_BASE = "https://bsky.social/xrpc"
DEFAULT_SESSION = (
    Path(os.environ.get("CLI_ANYTHING_BLUESKY_SESSION", ""))
    if os.environ.get("CLI_ANYTHING_BLUESKY_SESSION")
    else Path.home() / ".config" / "cli-anything-bluesky" / "session.json"
)


class AuthError(BackendError):
    """Raised when a session is missing or unusable."""


def load_session() -> dict:
    if not DEFAULT_SESSION.exists():
        raise AuthError("not logged in - run: cli-anything-bluesky login")
    try:
        data = _json.loads(DEFAULT_SESSION.read_text(encoding="utf-8"))
    except (ValueError, OSError) as e:
        raise AuthError(f"session file unreadable: {e}")
    if not data.get("accessJwt"):
        raise AuthError("session file has no access token - run login again")
    return data


def save_session(data: dict) -> Path:
    DEFAULT_SESSION.parent.mkdir(parents=True, exist_ok=True)
    DEFAULT_SESSION.write_text(_json.dumps(data, indent=2), encoding="utf-8")
    try:
        os.chmod(DEFAULT_SESSION, 0o600)
    except OSError:
        pass
    return DEFAULT_SESSION


def request(
    method: str,
    endpoint: str,
    body: dict | None = None,
    auth: bool = True,
    timeout: float = 20.0,
) -> dict:
    """One XRPC call. Auth endpoints attach the session bearer token."""
    url = endpoint if endpoint.startswith("http") else f"{API_BASE}/{endpoint}"
    data = _json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Content-Type", "application/json")
    if auth:
        session = load_session()
        req.add_header("Authorization", f"Bearer {session['accessJwt']}")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            raw = resp.read(4_000_000).decode("utf-8", errors="replace")
            return {"status": resp.status, "body": _json.loads(raw) if raw else {}}
    except urllib.error.HTTPError as e:
        raw = e.read(2_000_000).decode("utf-8", errors="replace")
        try:
            payload = _json.loads(raw)
        except ValueError:
            payload = {"raw": raw[:500]}
        raise BackendError(f"HTTP {e.code}: {payload.get('message', payload)}")


def login(identifier: str, app_password: str) -> dict:
    """Create a session with an App Password. Returns handle + did."""
    result = request(
        "POST",
        "com.atproto.server.createSession",
        body={"identifier": identifier, "appPassword": app_password},
        auth=False,
    )
    body = result["body"]
    save_session(body)
    return {"handle": body.get("handle"), "did": body.get("did"), "session_file": str(DEFAULT_SESSION)}


def post(text: str) -> dict:
    """Create one app.bsky.feed.post record on the authenticated repo."""
    session = load_session()
    record = {
        "$type": "app.bsky.feed.post",
        "text": text,
        "createdAt": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
    }
    return request(
        "POST",
        "com.atproto.repo.createRecord",
        body={"repo": session["did"], "collection": "app.bsky.feed.post", "record": record},
    )["body"]


