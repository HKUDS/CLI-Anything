def db_info(path: Path) -> dict:
    """Read-only overview. Never opens for write."""
    uri = f"file:{path.as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        tables = [
            r[0]
            for r in con.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
            ).fetchall()
        ]
        counts = {}
        for t in tables:
            counts[t] = con.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0]
        return {
            "path": str(path),
            "size_bytes": path.stat().st_size,
            "tables": tables,
            "row_counts": counts,
        }
    finally:
        con.close()


def db_schema(path: Path) -> dict:
    uri = f"file:{path.as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        out = {}
        for (t,) in con.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        ).fetchall():
            cols = con.execute(f'PRAGMA table_info("{t}")').fetchall()
            out[t] = [{"name": c[1], "type": c[2], "pk": bool(c[5])} for c in cols]
        return out
    finally:
        con.close()


def backup_db(path: Path, dest_dir: str | None = None) -> Path:
    """Timestamped copy before any write. Refuses to clobber an existing file."""
    stamp = time.strftime("%Y%m%d-%H%M%S")
    dest = Path(dest_dir) if dest_dir else path.parent
    dest.mkdir(parents=True, exist_ok=True)
    candidate = dest / f"{path.stem}.backup-{stamp}{path.suffix}"
    if candidate.exists():
        raise BackendError(f"backup target exists: {candidate}")
    shutil.copy2(path, candidate)
    return candidate


def run_query(path: Path, sql: str, limit: int = 100) -> dict:
    """Read-only SELECT only. Single statement. Row limit enforced."""
    stripped = sql.strip().rstrip(";").strip()
    head = stripped.lstrip("(").split(None, 1)[0].lower() if stripped else ""
    if head not in ("select", "with", "explain"):
        raise BackendError("only SELECT/WITH/EXPLAIN queries are allowed")
    if ";" in stripped:
        raise BackendError("multiple statements are not allowed")
    limit = max(1, min(int(limit), 10_000))
    uri = f"file:{path.as_posix()}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    try:
        cur = con.execute(stripped)
        rows = cur.fetchmany(limit + 1)
        truncated = len(rows) > limit
        rows = rows[:limit]
        cols = [d[0] for d in cur.description] if cur.description else []
        return {"columns": cols, "rows": [list(r) for r in rows], "truncated": truncated}
    except sqlite3.Error as e:
        raise BackendError(f"sqlite error: {e}") from e
    finally:
        con.close()


def export_table(path: Path, table: str, fmt: str, out: str) -> Path:
    schema = db_schema(path)
    if table not in schema:
        raise BackendError(f"unknown table: {table}")
    data = run_query(path, f'SELECT * FROM "{table}"', limit=1_000_000)
    dest = Path(out)
    if fmt == "json":
        dest.write_text(
            json.dumps([dict(zip(data["columns"], r)) for r in data["rows"]], indent=2),
            encoding="utf-8",
        )
    elif fmt == "csv":
        import csv

        with dest.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(data["columns"])
            w.writerows(data["rows"])
    else:
        raise BackendError(f"unknown format: {fmt}")
    return dest


def http_get(url: str, timeout: float = 10.0) -> dict:
    """Origin-scoped. Loopback is always allowed; remote hosts only if they
    were discovered during recon. An agent must not aim this at the internet."""
    parts = urlsplit(url)
    host = parts.hostname
    if host not in _LOOPBACK_HOSTS and parts.netloc not in ALLOWED_ORIGINS:
        raise BackendError(f"refusing URL outside discovered origins: {url}")
    import urllib.error
    import urllib.request

    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:
            body = resp.read(2_000_000).decode("utf-8", errors="replace")
            return {"status": resp.status, "url": url, "body": body}
    except urllib.error.HTTPError as e:
        body = e.read(2_000_000).decode("utf-8", errors="replace") if e.fp else ""
        return {"status": e.code, "url": url, "body": body}


