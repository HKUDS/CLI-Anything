GCODE_MAGIC = "; generated by OrcaSlicer"
MAX_HISTORY = 20


# ── G-code / statistics parsing ──────────────────────────────────


def parse_duration(text: str) -> float:
    """'1d 2h 3m 4s' -> seconds."""
    total = 0.0
    for num, unit in re.findall(r"(\d+(?:\.\d+)?)\s*([dhms])", text):
        total += float(num) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit]
    return total


def format_duration(seconds: float) -> str:
    s = int(round(seconds))
    d, s = divmod(s, 86400)
    h, s = divmod(s, 3600)
    m, s = divmod(s, 60)
    parts = [(d, "d"), (h, "h"), (m, "m"), (s, "s")]
    return " ".join(f"{v}{u}" for v, u in parts if v) or "0s"


def _read_head_tail(path: str, head: int = 8192, tail: int = 16384) -> str:
    size = os.path.getsize(path)
    with open(path, "rb") as fh:
        first = fh.read(head)
        if size > head + tail:
            fh.seek(-tail, os.SEEK_END)
            last = fh.read(tail)
        else:
            last = b""
    return (first + b"\n" + last).decode("utf-8", errors="replace")


_NUM = r"([-+]?\d+(?:\.\d+)?)"


def gcode_info(path: str) -> Dict[str, Any]:
    """Verify and summarise a G-code file produced by OrcaSlicer."""
    if not os.path.isfile(path):
        raise FileNotFoundError(f"G-code file not found: {path}")
    size = os.path.getsize(path)
    if size == 0:
        raise ValueError(f"G-code file is empty: {path}")
    text = _read_head_tail(path)
    if GCODE_MAGIC not in text[:4096]:
        raise ValueError(f"{path} does not look like OrcaSlicer G-code (missing '{GCODE_MAGIC}' header).")

    info: Dict[str, Any] = {"path": os.path.abspath(path), "bytes": size}
    m = re.search(r"; generated by OrcaSlicer ([^\s]+)", text)
    info["generator_version"] = m.group(1) if m else None

    def grab(pattern: str, cast=float):
        mm = re.search(pattern, text)
        return cast(mm.group(1)) if mm else None

    info["layers"] = grab(r"; total layers count = (\d+)", int) or grab(r"; total layer number: (\d+)", int)
    info["max_z"] = grab(r"; max_z_height: " + _NUM)
    info["filament_mm"] = grab(r"; filament used \[mm\] = " + _NUM)
    info["filament_cm3"] = grab(r"; filament used \[cm3\] = " + _NUM)
    info["filament_g"] = grab(r"; total filament used \[g\] = " + _NUM) or grab(r"; filament used \[g\] = " + _NUM)
    info["filament_cost"] = grab(r"; total filament cost = " + _NUM)
    mt = re.search(r"; estimated printing time \(normal mode\) = ([^\n]+)", text)
    info["print_time"] = mt.group(1).strip() if mt else None
    info["print_time_s"] = parse_duration(mt.group(1)) if mt else None

    extrusion_moves = 0
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith(("G1 ", "G2 ", "G3 ")) and " E" in line:
                extrusion_moves += 1
    info["extrusion_moves"] = extrusion_moves
    if extrusion_moves == 0:
        raise ValueError(f"{path} contains no extrusion moves — the slice is empty.")
    return info


def load_statistics(path: str) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


# ── Pipeline ─────────────────────────────────────────────────────


def default_outdir(project: Dict[str, Any], project_path: Optional[str]) -> str:
    if project["slice"].get("outdir"):
        return os.path.abspath(project["slice"]["outdir"])
    base = os.path.dirname(os.path.abspath(project_path)) if project_path else os.getcwd()
    safe = re.sub(r"[^A-Za-z0-9._-]+", "_", project["name"]) or "project"
    return os.path.join(base, f"{safe}_output")


def prepare_settings(project: Dict[str, Any], settings_dir: str) -> Dict[str, Any]:
    """Materialise machine/process/filament JSON. Returns paths and flattened presets."""
    refs = project["profiles"]
    dirs = refs.get("dirs")
    ov = project["overrides"]
    os.makedirs(settings_dir, exist_ok=True)
    machine = os.path.join(settings_dir, "machine.json")
    process = os.path.join(settings_dir, "process.json")
    schema = config_mod.get_schema()
    for kind, ref, path in (("machine", refs["machine"], machine), ("process", refs["process"], process)):
        merged = prof.materialize(kind, ref, ov[kind], path, dirs)
        migrated = prof.migrate_legacy_keys(merged, schema)
        if migrated != merged:
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(migrated, fh, indent=2, ensure_ascii=False)
    filaments = []
    multi = len(refs["filaments"]) > 1
    for i, ref in enumerate(refs["filaments"], start=1):
        p = os.path.join(settings_dir, f"filament_{i}.json")
        merged = prof.materialize("filament", ref, ov["filament"], p, dirs)
        if multi:   # all per-filament vectors must be present in every slot
            with open(p, "w", encoding="utf-8") as fh:
                json.dump(config_mod.complete_filament(merged), fh, indent=2, ensure_ascii=False)
        filaments.append(p)
    return {"machine": machine, "process": process, "filaments": filaments}


_TILTING_OPS = {"scale", "rotate_x", "rotate_y"}


def needs_ensure_on_bed(project: Dict[str, Any]) -> bool:
    """True when we must add --ensure-on-bed ourselves (auto policy, tilting transforms)."""
    if not project["slice"].get("auto_ensure_on_bed", True):
        return False
    ops = {t["op"] for t in project["transforms"]}
    return bool(ops & _TILTING_OPS) and "ensure_on_bed" not in ops


def build_args(project: Dict[str, Any], settings: Dict[str, Any], outdir: str, plate: int,
               export_3mf_name: Optional[str], strict: bool, no_check: bool) -> List[str]:
    args = ["--slice", str(plate), "--outputdir", outdir, "--export-statistics",
            "--load-settings", f"{settings['machine']};{settings['process']}",
            "--load-filaments", ";".join(settings["filaments"])]
    args += tf.build_args(project["transforms"], project["models"])
    if needs_ensure_on_bed(project):
        # Scale/tilt pivot around the object centre; without this OrcaSlicer silently
        # clips whatever ends up below the bed (e.g. rotate-x 90 of a 30mm box prints 5mm).
        args.append("--ensure-on-bed")
    if strict:
        args.append("--strict")
    if no_check:
        args.append("--no-check")
    if export_3mf_name:
        args += ["--export-3mf", export_3mf_name]
    if any(m.get("filament") for m in project["models"]):
        args += ["--load-filament-ids", ",".join(str(m.get("filament") or 1) for m in project["models"])]
    args += [m["path"] for m in project["models"]]
    return args


def _check_models(project: Dict[str, Any]) -> None:
    if not project["models"]:
        raise ValueError("Project has no models. Use 'model add FILE' first.")
    missing = [m["path"] for m in project["models"] if not os.path.isfile(m["path"])]
    if missing:
        raise FileNotFoundError("Model file(s) missing: " + ", ".join(missing))


def _clean_outputs(outdir: str) -> None:
    for pattern in ("plate_*.gcode", "plate_*.statistics.json", "result.json"):
        for f in glob.glob(os.path.join(outdir, pattern)):
            os.remove(f)


def slice_project(project: Dict[str, Any], project_path: Optional[str] = None,
                  outdir: Optional[str] = None, plate: Optional[int] = None,
                  export_3mf: Optional[str] = None, strict: Optional[bool] = None,
                  no_check: Optional[bool] = None, timeout: int = 900,
                  record: bool = True) -> Dict[str, Any]:
    """Slice the project with the real OrcaSlicer and return verified results."""
    _check_models(project)
    opts = project["slice"]
    plate = opts.get("plate", 0) if plate is None else plate
    if plate < 0:
        raise ValueError("--plate must be 0 (all) or a plate number >= 1.")
    plate_adjusted = False
    if plate == 0 and tf.repetitions_need_plate(project["transforms"], project["models"]):
        plate, plate_adjusted = 1, True   # native --repetitions refuses "slice all plates"
    strict = opts.get("strict", False) if strict is None else strict
    no_check = opts.get("no_check", False) if no_check is None else no_check
    if strict and no_check:
        raise ValueError("--strict cannot be combined with --no-check.")

    out = os.path.abspath(outdir) if outdir else default_outdir(project, project_path)
    os.makedirs(out, exist_ok=True)
    _clean_outputs(out)
    settings = prepare_settings(project, os.path.join(out, "settings"))

    threemf_name = None
    if export_3mf:
        export_3mf = os.path.abspath(export_3mf)
        threemf_name = os.path.basename(export_3mf)
    args = build_args(project, settings, out, plate, threemf_name, strict, no_check)
    res = backend.run(args, cwd=out, timeout=timeout)
    if not res["ok"]:
        backend.raise_for_result(res)

    pattern = f"plate_{plate}.gcode" if plate else "plate_*.gcode"
    gcodes = sorted(glob.glob(os.path.join(out, pattern)))
    if not gcodes:
        raise RuntimeError(
            f"OrcaSlicer exited 0 but produced no G-code in {out} (plate={plate}). "
            f"Does that plate exist? Output: {(res['stdout'] + res['stderr']).strip()[-300:]}")

    plates = []
    for g in gcodes:
        info = gcode_info(g)
        pnum = int(re.search(r"plate_(\d+)\.gcode$", g).group(1))
        info["plate"] = pnum
        sp = os.path.join(out, f"plate_{pnum}.statistics.json")
        info["statistics"] = sp if os.path.isfile(sp) else None
        if info["statistics"]:
            summ = load_statistics(sp).get("summary", {})
            if summ.get("time"):
                info["print_time_s"] = round(float(summ["time"]), 1)
                info["print_time"] = format_duration(summ["time"])
            if summ.get("travel_distance") is not None:
                info["travel_distance_mm"] = summ["travel_distance"]
        plates.append(info)

    export_path = None
    if export_3mf:
        produced = os.path.join(out, threemf_name)
        if not os.path.isfile(produced):
            raise RuntimeError(f"OrcaSlicer did not produce the 3MF project: {produced}")
        if os.path.abspath(produced) != export_3mf:
            os.makedirs(os.path.dirname(export_3mf), exist_ok=True)
            shutil.move(produced, export_3mf)
        export_path = export_3mf

    warnings = [ln.strip() for ln in (res["stdout"] + "\n" + res["stderr"]).splitlines()
                if re.search(r"warning|\bneeds? support", ln, re.I)]
    result = {
        "ok": True,
        "outdir": out,
        "settings": settings,
        "plates": plates,
        "export_3mf": export_path,
        "warnings": warnings,
        "auto_ensure_on_bed": needs_ensure_on_bed(project),
        "plate_adjusted": plate_adjusted,
        "duration_s": res["duration_s"],
        "orcaslicer_version": backend.get_version(),
        "command": res["command"],
    }
    if record:
        record_history(project, result)
    return result


def record_history(project: Dict[str, Any], result: Dict[str, Any]) -> None:
    from cli_anything.orcaslicer.core.project import fingerprint
    entry = {
        "timestamp": datetime.now().isoformat(),
        "outdir": result["outdir"],
        "fingerprint": fingerprint(project),
        "plates": [{k: p.get(k) for k in ("plate", "path", "layers", "print_time_s", "print_time",
                                           "filament_g", "filament_mm", "filament_cm3", "statistics")}
                   for p in result["plates"]],
        "export_3mf": result.get("export_3mf"),
    }
    hist = project.setdefault("history", [])
    hist.append(entry)
    del hist[:-MAX_HISTORY]


def last_slice(project: Dict[str, Any]) -> Dict[str, Any]:
    if not project.get("history"):
        raise RuntimeError("No slice has been run yet. Use 'slice run' first.")
    return project["history"][-1]


def feature_stats(project: Dict[str, Any], plate: int = 1) -> Dict[str, Any]:
    """Per-feature / per-object statistics of the most recent slice."""
    entry = last_slice(project)
    for p in entry["plates"]:
        if p["plate"] == plate:
            if not p.get("statistics") or not os.path.isfile(p["statistics"]):
                raise FileNotFoundError(f"Statistics file missing for plate {plate}; re-run 'slice run'.")
            data = load_statistics(p["statistics"])
            return {
                "plate": plate,
                "summary": data.get("summary", {}),
                "objects": data.get("objects", []),
                "layer_count": len(data.get("layers", [])),
                "units": data.get("units", {}),
            }
    raise IndexError(f"Plate {plate} not in the last slice (plates: "
                     f"{[p['plate'] for p in entry['plates']]}).")
