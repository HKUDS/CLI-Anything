class TestTransforms:
    def test_scale(self, proj):
        assert T.add_transform(proj, "scale", "2")["value"] == 2.0

    @pytest.mark.parametrize("v", [0, -1, "abc", None])
    def test_scale_invalid(self, proj, v):
        with pytest.raises(ValueError):
            T.add_transform(proj, "scale", v)

    @pytest.mark.parametrize("op", ["rotate", "rotate_x", "rotate_y"])
    def test_rotations(self, proj, op):
        assert T.add_transform(proj, op, -45)["value"] == -45.0

    def test_rotation_not_number(self, proj):
        with pytest.raises(ValueError, match="needs a number"):
            T.add_transform(proj, "rotate", "left")

    @pytest.mark.parametrize("op", ["orient", "arrange"])
    def test_int01(self, proj, op):
        assert T.add_transform(proj, op, 1)["value"] == 1
        with pytest.raises(ValueError):
            T.add_transform(proj, op, 2)
        with pytest.raises(ValueError):
            T.add_transform(proj, op, "x")

    def test_repetitions(self, proj):
        assert T.add_transform(proj, "repetitions", 3)["value"] == 3
        with pytest.raises(ValueError):
            T.add_transform(proj, "repetitions", 0)
        with pytest.raises(ValueError):
            T.add_transform(proj, "repetitions", "many")

    def test_vec3(self, proj):
        assert T.add_transform(proj, "ground_face_normal", "1, 0,0")["value"] == "1,0,0"
        for bad in ("1,0", "a,b,c", "1,2,3,4", ""):
            with pytest.raises(ValueError):
                T.add_transform(proj, "ground_face_point", bad)

    def test_unknown_op(self, proj):
        with pytest.raises(ValueError, match="Unknown transform"):
            T.add_transform(proj, "explode", 1)

    def test_flags_idempotent(self, proj):
        T.add_transform(proj, "ensure_on_bed")
        T.add_transform(proj, "ensure_on_bed")
        T.add_transform(proj, "repair")
        assert len(proj["transforms"]) == 2

    def test_non_flags_stack(self, proj):
        T.add_transform(proj, "rotate_x", 90)
        T.add_transform(proj, "rotate_x", 90)
        assert len(proj["transforms"]) == 2

    def test_build_args_order_preserved(self, proj):
        T.add_transform(proj, "rotate_x", 90)
        T.add_transform(proj, "ground_largest_face")
        T.add_transform(proj, "scale", 1.5)
        assert T.build_args(proj["transforms"]) == [
            "--rotate-x", "90", "--ground-largest-face", "--scale", "1.5"]

    def test_build_args_empty(self):
        assert T.build_args([]) == []

    def test_copies_use_clone_objects_for_meshes(self, proj):
        T.add_transform(proj, "rotate", 10)
        T.add_transform(proj, "repetitions", 3)
        models = [{"path": "/a.stl"}, {"path": "/b.OBJ"}]
        assert T.build_args(proj["transforms"], models) == ["--rotate", "10", "--clone-objects", "3,3"]
        assert T.repetitions_need_plate(proj["transforms"], models) is False

    def test_copies_use_native_repetitions_for_3mf(self, proj):
        T.add_transform(proj, "repetitions", 2)
        models = [{"path": "/a.3mf"}]
        assert T.build_args(proj["transforms"], models) == ["--repetitions", "2"]
        assert T.repetitions_need_plate(proj["transforms"], models) is True

    def test_copies_mixed_3mf_and_mesh_rejected(self, proj):
        T.add_transform(proj, "repetitions", 2)
        with pytest.raises(ValueError, match="mix"):
            T.build_args(proj["transforms"], [{"path": "/a.3mf"}, {"path": "/b.stl"}])

    def test_copies_without_models_rejected(self, proj):
        T.add_transform(proj, "repetitions", 2)
        with pytest.raises(ValueError, match="at least one model"):
            T.build_args(proj["transforms"], [])

    def test_last_repetitions_wins(self, proj):
        T.add_transform(proj, "repetitions", 2)
        T.add_transform(proj, "repetitions", 4)
        assert T.copies_count(proj["transforms"]) == 4
        assert T.build_args(proj["transforms"], [{"path": "/a.stl"}]) == ["--clone-objects", "4"]

    def test_one_copy_emits_nothing(self, proj):
        T.add_transform(proj, "repetitions", 1)
        assert T.build_args(proj["transforms"], [{"path": "/a.stl"}]) == []

    def test_clear(self, proj):
        T.add_transform(proj, "scale", 2)
        assert T.clear_transforms(proj) == 1 and proj["transforms"] == []

    def test_every_op_has_cli_flag(self):
        for op, (flag, _) in T.OPS.items():
            assert flag.startswith("--")


