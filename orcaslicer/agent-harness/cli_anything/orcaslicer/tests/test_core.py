class TestSession:
    def test_requires_project(self):
        with pytest.raises(RuntimeError, match="No project loaded"):
            Session().get_project()

    def test_undo_redo(self, proj):
        s = Session()
        s.set_project(proj)
        s.snapshot("one")
        proj["name"] = "changed"
        s.project["name"] = "changed"
        assert s.undo() == "one"
        assert s.project["name"] == "unit"
        assert s.redo() == "redo point"
        assert s.project["name"] == "changed"

    def test_undo_empty(self, proj):
        s = Session()
        s.set_project(proj)
        with pytest.raises(RuntimeError, match="Nothing to undo"):
            s.undo()

    def test_redo_empty(self, proj):
        s = Session()
        s.set_project(proj)
        with pytest.raises(RuntimeError, match="Nothing to redo"):
            s.redo()

    def test_new_edit_clears_redo(self, proj):
        s = Session()
        s.set_project(proj)
        s.snapshot("a")
        s.undo()
        s.snapshot("b")
        with pytest.raises(RuntimeError):
            s.redo()

    def test_max_undo(self, proj):
        s = Session()
        s.set_project(proj)
        for i in range(Session.MAX_UNDO + 10):
            s.snapshot(str(i))
        assert len(s._undo_stack) == Session.MAX_UNDO

    def test_snapshot_marks_modified(self, proj):
        s = Session()
        s.set_project(proj)
        assert not s._modified
        s.snapshot("x")
        assert s._modified

    def test_status(self, proj):
        s = Session()
        assert s.status()["has_project"] is False
        s.set_project(proj, "/x.json")
        st = s.status()
        assert st["project_name"] == "unit" and st["project_path"] == "/x.json"

    def test_history_listing(self, proj):
        s = Session()
        s.set_project(proj)
        s.snapshot("first")
        s.snapshot("second")
        assert [h["description"] for h in s.list_history()] == ["second", "first"]

    def test_save_session(self, tmp, proj):
        s = Session()
        s.set_project(proj)
        with pytest.raises(ValueError, match="No save path"):
            s.save_session()
        path = str(tmp / "s.json")
        assert s.save_session(path) == path
        assert json.load(open(path))["name"] == "unit"
        assert not s._modified

    def test_save_without_project(self):
        with pytest.raises(RuntimeError):
            Session().save_session("/tmp/x.json")

    def test_locked_save_overwrites_shorter(self, tmp):
        path = str(tmp / "l.json")
        _locked_save_json(path, {"a": "x" * 500})
        _locked_save_json(path, {"a": 1})
        assert json.load(open(path)) == {"a": 1}  # truncated inside the lock

    def test_locked_save_creates_dirs(self, tmp):
        path = str(tmp / "deep" / "er" / "l.json")
        _locked_save_json(path, {"ok": True})
        assert os.path.isfile(path)


